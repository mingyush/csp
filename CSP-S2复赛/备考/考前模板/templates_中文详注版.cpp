// 2. Dijkstra：单源最短路（优先队列版本）
// ==========================================================
/*
 * 【什么时候用】
 *   给定一个起点 source，求它到所有其他点的最短距离。
 *   可以是有向图或无向图，但每条边权必须 >= 0！
 *
 * 【不能用的情况】
 *   有负权边时，普通 Dijkstra 不保证正确；
 *   求最长路、必须经过指定点等问题，也不能直接把它当答案。
 *
 * 【输入】
 *   n：顶点数，编号 1..n。
 *   source：起点编号。
 *   g[u]：从 u 出发的边列表，每条边是 {终点 v, 边权 w}。
 *
 * 【建图示例】
 *   vector<vector<pair<int,ll>>> g(n+1);
 *   g[1].push_back({2, 7}); // 有向边 1 -> 2，权重为 7
 *   g[2].push_back({3, 4}); // 有向边 2 -> 3，权重为 4
 *   // 若无向边 1--2，需要同时 g[1].push_back({2,7}) 和
 *   // g[2].push_back({1,7})。
 *   vector<ll> dist = dijkstra(n, 1, g);
 *   // dist[1] = 0, dist[2] = 7, dist[3] = 11。
 *
 * 【理解】
 *   dist[v] 是当前找到的“起点到 v 的最短距离候选值”。
 *   每次从小根堆中取出最小的候选距离，尝试用它更新邻居。
 *   如果“经过 u 到 v”比原有 dist[v] 短，就发生一次松弛。
 *
 * 【复杂度】邻接表 + 优先队列：约 O((n+m)log n)，m 为边数。
 * 【易错】
 *   - INF 表示当前不可达；不能把 INF 当真实答案输出。
 *   - 边权以及路径长度必须在 long long 和 INF 的安全范围内，
 *     这里假设所有可能的最短距离、候选距离均不会溢出且小于 INF。
 *   - 本模板的 g 必须至少有 n+1 个元素，点编号必须有效。
 */
vector<ll> dijkstra(int n, int source,
                    const vector<vector<pair<int, ll>>>& g) {
    const ll INF = (1LL << 62); // 很大的数，表示“尚不可达”
    vector<ll> dist(n + 1, INF); // 初始到每个点的距离都未知

    // 小根堆：pair 的 first 是“距离”，second 是“顶点编号”。
    // greater 让最小距离的状态优先弹出。
    priority_queue<pair<ll, int>,
                   vector<pair<ll, int>>,
                   greater<pair<ll, int>>> pq;

    dist[source] = 0;     // 起点到自身的最短路为 0
    pq.push({0, source}); // 把起点放入优先队列

    while (!pq.empty()) {
        ll du = pq.top().first;  // 此状态记录的起点到 u 的距离
        int u = pq.top().second; // 此状态对应的顶点
        pq.pop();

        // 同一个点可能多次入堆；旧的较差距离不再处理。
        if (du != dist[u]) continue;

        for (auto e : g[u]) { // 枚举从 u 出发的所有边 u -> v
            int v = e.first;  // 邻居 v
            ll w = e.second;  // 边权 w，必须 >= 0

            // “先走到 u，再走 u->v”是否比已知路线更短？
            if (dist[v] > du + w) {
                dist[v] = du + w;        // 更新 v 的最短距离候选
                pq.push({dist[v], v});  // 候选变好，重新入堆
            }
        }
    }
    return dist; // dist[v]：从 source 到 v 的最短距离
}

