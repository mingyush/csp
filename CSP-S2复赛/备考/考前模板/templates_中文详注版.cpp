// 5. KMP 前缀函数 prefixFunction（只计算 pi 数组）
// ==========================================================
/*
 * 【什么时候用】
 *   - 字符串中的最长“相同真前缀与后缀”。
 *   - 求最小周期、理解 KMP 字符串匹配中的失败回退。
 *
 * 【注意】
 *   这是 KMP 的前缀函数模板，不是完整的“在文本中查找模式串”函数！
 *   如果题目要求返回所有匹配位置，需要另外编写匹配部分。
 *
 * 【pi[i] 的含义】
 *   在子串 s[0..i] 中：最长的、非整个子串自身的前缀，
 *   同时也是后缀的长度。
 *   例如 s="ababa"，返回 pi=[0,0,1,2,3]。
 *   最后 pi[4]=3，表示 "aba" 既是前缀，也是后缀。
 *
 * 【关键思想】
 *   假设目前已经匹配了 j 个前缀字符；若 s[i] != s[j]，
 *   不必从 0 重新试，而是根据 pi[j-1] 跳到下一个可能的长度。
 *   这叫“失配回退”。
 *
 * 【调用】vector<int> pi = prefixFunction("ababa");
 * 【复杂度】O(|s|) 时间，O(|s|) 空间；下标为 0..n-1。
 * 【易错】pi 记录“长度”而非“最后字符的下标”；空串返回空数组。
 */
vector<int> prefixFunction(const string& s) {
    vector<int> pi(s.size(), 0); // pi[0]=0：单个字符不存在非空真前后缀

    for (int i = 1; i < (int)s.size(); ++i) {
        int j = pi[i - 1]; // 先尝试延续上一个位置的最长匹配长度

        // 如果下一个字符不匹配，就尝试更短的候选前后缀。
        while (j > 0 && s[i] != s[j]) {
            j = pi[j - 1]; // 回退，不需要逐个长度从头重试
        }

        if (s[i] == s[j]) ++j; // 这次成功多匹配一个字符
        pi[i] = j;            // 记录 s[0..i] 的最长相同真前后缀长度
    }
    return pi;
}

