// 6. Manacher（马拉车）：最长“连续回文子串”的长度
// ==========================================================
/*
 * 【什么时候用】
 *   想求一个字符串中最长的连续回文片段长度，要求 O(n) 复杂度。
 *   例："abba" -> 4，"abc" -> 1，"abacaba" -> 7，"" -> 0。
 *
 * 【绝对要区分】
 *   “子串”必须连续；“子序列”可以不连续。
 *   这份函数不能直接求最长回文子序列、回文路径或最少回文划分。
 *
 * 【输入限制】
 *   原字符串不能含 '@'、'#'、'$'，因为本版本把它们用作特殊字符。
 *   普通小写字母字符串没有问题。如果题目允许这三种字符，
 *   不能原样套用本模板，应另选不会冲突的处理方式。
 *
 * 【为什么插入 #】
 *   原串 "abba" 变成 "@#a#b#b#a#$"：
 *   相邻原字符中间加入 #，可以把偶数长度和奇数长度回文统一处理。
 *   左侧 @ 与右侧 $ 是不同的哨兵，用来停止向两边扩展。
 *
 * 【p[i] 的意思】
 *   在处理后的字符串 t 里，以位置 i 为中心，最多能向左右
 *   对称扩展多少步（不包含中心）。
 *   由于 # 的插入方式，这个扩展步数恰好等于原串的回文子串长度。
 *
 * 【center/right 的意思】
 *   center：目前已知、向右覆盖最远的回文中心；
 *   right：这个回文在 t 中的最右端下标（包含该下标）。
 *   若 i < right，可以借助 i 关于 center 的镜像位置，
 *   先推测一部分回文半径，再继续向外扩展，达到 O(n)。
 *
 * 【返回值】最长连续回文子串长度，不返回具体位置。
 * 【复杂度】O(n) 时间，O(n) 额外空间。
 * 【易错】边界哨兵不能冲突；这里的下标属于新串 t，不是原串 s。
 */
int longestPalSubstring(const string& s) {
    // 预处理：把所有回文统一为“以单个字符为中心”的形式。
    string t = "@#";       // @ 是左边界哨兵，# 是分隔符
    for (char c : s) {
        t += c;             // 加入一个原字符
        t += '#';           // 在字符右侧加一个分隔符
    }
    t += '$';               // $ 是右边界哨兵（与 @ 不同）

    vector<int> p(t.size(), 0); // p[i]：t 中以 i 为中心的回文半径
    int center = 0;            // 当前最靠右回文的中心
    int right = 0;             // 当前最靠右回文覆盖的右端（含端点）
    int best = 0;              // 原字符串最长回文子串长度

    // 不处理首尾哨兵；它们只负责让扩展在边界自然停止。
    for (int i = 1; i + 1 < (int)t.size(); ++i) {
        if (i < right) {
            // 镜像位置 mirror = 2*center-i。
            // 镜像半径可以复用，但不能越过当前已知的右边界。
            p[i] = min(right - i, p[2 * center - i]);
        }

        // 继续从已知半径之外向两侧扩展；字符一样就扩大半径。
        while (t[i - p[i] - 1] == t[i + p[i] + 1]) {
            ++p[i];
        }

        // 如果以 i 为中心的回文向右延伸得更远，更新最右覆盖范围。
        if (i + p[i] > right) {
            center = i;
            right = i + p[i];
        }

        // 在本题的预处理方式下，p[i] 就是原串对应回文的长度。
        best = max(best, p[i]);
    }
    return best;
}

