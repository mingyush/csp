// 4. 拓扑排序 Topological Sort（Kahn 算法）
// ==========================================================
/*
 * 【什么时候用】
 *   有向图中存在“先做 A 才能做 B”的依赖关系，要求给出一个合法顺序。
 *   例如课程先修、任务执行顺序、判断有向图是否包含环。
 *
 * 【输入】
 *   g[u] 存储所有有向边 u -> v，表示“u 必须排在 v 前面”。
 *
 * 【思路】
 *   indeg[v] 是 v 的入度，也就是还有多少个前置条件未完成。
 *   先把所有入度为 0 的点放入队列；取出一个点，相当于完成它，
 *   从而把它指向的后续节点入度减 1，降到 0 就可以入队。
 *
 * 【返回值】
 *   如果返回的 order.size()==n：得到一个合法拓扑序；
 *   如果 order.size()<n：图中存在有向环，无法排出全部节点。
 *   注意：合法的拓扑序可能不唯一；本模板不保证字典序最小。
 *
 * 【调用示例】
 *   vector<vector<int>> g(n+1);
 *   g[1].push_back(3); // 1 必须在 3 前
 *   g[2].push_back(3); // 2 必须在 3 前
 *   auto order = topoOrder(n, g);
 *   if ((int)order.size() < n) { cout << "cycle"; }
 *
 * 【复杂度】O(n+m)，m 是有向边数。
 * 【易错】只用于有向边；无向图不能直接按此定义排序。
 */
vector<int> topoOrder(int n, const vector<vector<int>>& g) {
    vector<int> indeg(n + 1, 0); // indeg[v]：当前还有多少条入边
    vector<int> order;           // 最后得到的拓扑序

    // 第一次扫描所有边，统计每个点的入度。
    for (int u = 1; u <= n; ++u) {
        for (int v : g[u]) {
            ++indeg[v]; // 发现一条 u->v，v 的前置条件数量 +1
        }
    }

    queue<int> q;
    for (int u = 1; u <= n; ++u) {
        if (indeg[u] == 0) q.push(u); // 没有前置条件，可以先完成
    }

    while (!q.empty()) {
        int u = q.front();
        q.pop();
        order.push_back(u); // 确定 u 可以放在当前拓扑序的下一位

        for (int v : g[u]) {
            --indeg[v];                 // 完成 u，v 少了一个前置条件
            if (indeg[v] == 0) q.push(v); // v 的所有前置条件都完成
        }
    }
    return order; // 若长度不足 n，则说明有向图里有环
}

