// 1. 并查集 DSU（Disjoint Set Union）
// ==========================================================
/*
 * 【什么时候用】
 *   - 判断两点当前是否在同一连通块中。
 *   - 不断加入“连接关系”，并查询集合是否已经连通。
 *   - Kruskal 最小生成树：按边权从小到大遍历，若两端不连通就加入。
 *
 * 【不适用】
 *   - 普通并查集不能直接删除边，也不能直接回答“最短路是多少”。
 *
 * 【核心想法】
 *   每个集合由一个“代表元”（根）标识。
 *   find(x) 找到 x 所属集合的根；unite(a,b) 把两个不同集合合并。
 *   路径压缩 + 按大小合并，使每次操作均摊非常快，约 O(α(n))。
 *
 * 【调用示例】
 *   DSU dsu(n);                 // 先初始化 n 个点，编号 1..n
 *   dsu.unite(1, 3);            // 连接 1、3
 *   dsu.unite(3, 5);            // 连接 3、5
 *   bool ok = (dsu.find(1) == dsu.find(5)); // true
 *   bool merged = dsu.unite(1, 5); // false：本来已连通
 *
 * 【返回值】
 *   unite(a,b) = true  表示原本不属于同一集合，这次真的合并了；
 *   unite(a,b) = false 表示已经在同一集合，没发生新的合并。
 *
 * 【易错】n+1 是因为使用 1..n；查询时比较 find，不能直接比较 parent。
 */
struct DSU {
    vector<int> parent; // parent[x]：x 的父节点；根满足 parent[x] == x
    vector<int> sz;     // sz[x]：仅当 x 是根时，表示该集合的元素数量

    DSU(int n) : parent(n + 1), sz(n + 1, 1) {
        // 一开始每个点各自成集合，parent[x] = x。
        iota(parent.begin(), parent.end(), 0);
    }

    int find(int x) {
        if (parent[x] == x) return x; // x 已经是根
        // 路径压缩：把沿途节点的父亲直接设为根，后续查找更快。
        return parent[x] = find(parent[x]);
    }

    bool unite(int a, int b) {
        a = find(a); // 先找到 a 所在集合的根
        b = find(b); // 再找到 b 所在集合的根
        if (a == b) return false; // 根相同：两个点早已连通

        // 按大小合并：小集合接到大集合下面，避免树太高。
        if (sz[a] < sz[b]) swap(a, b);
        parent[b] = a;  // b 的根现在指向 a 的根
        sz[a] += sz[b]; // 更新新根所代表的集合大小
        return true;    // 本次确实把两个集合合成了一个
    }
};

