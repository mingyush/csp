// 7. 快速幂：计算 a^e % mod
// ==========================================================
/*
 * 【什么时候用】
 *   指数 e 特别大，无法直接乘 e 次，要求快速算 a 的 e 次方取模。
 *   常见于组合计数、模运算、数论题中的幂次计算。
 *
 * 【核心想法（二进制拆指数）】
 *   e 的二进制每一位都代表某个 2 的幂次。
 *   例如 13 = 8+4+1，所以 a^13 = a^8 * a^4 * a。
 *   每轮把 a 平方，把 e 右移一位；如果这一位是 1，就乘进答案。
 *
 * 【调用示例】
 *   modPow(2,10,1000) -> 24（2^10=1024，模 1000 得 24）。
 *   modPow(5,0,7)    -> 1（指数为 0）。
 *   modPow(-2,3,5)   -> 2（-8 模 5 按非负余数计算为 2）。
 *
 * 【参数限制】
 *   e >= 0，1 <= mod <= 2,000,000,000；a 可正可负。
 *   由于 a 在计算前会取模，此上界保证两个模数内的数相乘时
 *   不超过有符号 long long 的范围。模数非常大时要另用防溢出乘法。
 *
 * 【复杂度】O(log e) 时间，O(1) 空间。
 * 【易错】必须在乘法之后立刻 % mod；mod=1 时答案永远为 0。
 */
ll modPow(ll a, ll e, ll mod) {
    a = (a % mod + mod) % mod; // 把负底数规范成 0..mod-1
    ll ans = 1 % mod;         // 乘法单位元；mod=1 时这里为 0

    while (e > 0) {
        if (e & 1) {          // e 的当前最低二进制位为 1
            ans = ans * a % mod; // 把这一位代表的幂乘进答案
        }
        a = a * a % mod;      // 从 a^(2^k) 更新到 a^(2^(k+1))
        e >>= 1;             // 右移一位，相当于 e/=2
    }
    return ans;
}

