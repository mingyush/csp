// 3. 树状数组 Fenwick / BIT
// ==========================================================
/*
 * 【什么时候用】
 *   数组经常执行以下两种操作：
 *   ① 把某个位置 a[i] 增加 delta（单点加法）。
 *   ② 查询 a[1]+...+a[r]（前缀和）或 a[l]+...+a[r]（区间和）。
 *
 * 【不适用】
 *   这份最简模板不能直接实现“区间赋值”“区间最小值”或
 *   “区间加、区间求和”的完整功能，这些需要其他技巧或结构。
 *
 * 【思路】
 *   bit[i] 并不直接存 a[i]，而是存结尾在 i 的一段区间之和。
 *   lowbit(i) = i & -i，表示 i 在二进制中最低位的 1 所对应的值。
 *   例如 i=12(二进制 1100)，lowbit(12)=4。
 *   修改 i 时不断 i += lowbit(i)；求前缀和时不断 i -= lowbit(i)。
 *
 * 【调用示例】
 *   Fenwick fw(5);    // 位置 1..5 初始值都是 0
 *   fw.add(2, 3);     // a[2] += 3
 *   fw.add(4, 5);     // a[4] += 5
 *   fw.sum(4);        // 8
 *   fw.rangeSum(2,3); // 3
 *   fw.add(2,-1);     // a[2] 从 3 改成 2（加 -1）
 *
 * 【复杂度】add、sum、rangeSum 均为 O(log n)，空间 O(n)。
 * 【最容易出错的点】
 *   - 必须用下标 1..n！add(0,delta) 会陷入死循环。
 *   - 调用 add 时保证 1<=i<=n，调用 sum 时保证 0<=i<=n。
 *   - rangeSum(l,r) 假设 1<=l<=r<=n，区间两端都包括。
 *   - “改成 x”不是 add(i,x)，应该先求旧值再加差值。
 */
struct Fenwick {
    int n;          // 数组有效下标为 1..n
    vector<ll> bit; // 内部树状数组；bit[0] 不参与运算

    Fenwick(int n_) : n(n_), bit(n_ + 1, 0) {} // 初始化为全 0

    void add(int i, ll delta) {
        // 给 a[i] 增加 delta，并更新所有覆盖位置 i 的树状数组块。
        for (; i <= n; i += i & -i) {
            bit[i] += delta;
        }
    }

    ll sum(int i) const {
        // 求原数组 a[1]+a[2]+...+a[i]；i=0 时答案为 0。
        ll res = 0;
        for (; i > 0; i -= i & -i) {
            res += bit[i]; // 收集当前这一块的区间和
        }
        return res;
    }

    ll rangeSum(int l, int r) const {
        // [l,r] = [1,r] - [1,l-1]，左右端点均包含。
        return sum(r) - sum(l - 1);
    }
};

